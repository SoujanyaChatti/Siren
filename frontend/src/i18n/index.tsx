export type Strings = typeof S.en
const Ctx = createContext<{ lang: Lang; t: Strings; setLang: (l: Lang) => void }>({ lang: 'en', t: S.en, setLang: () => {} })

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem('siren-lang')
    if (saved === 'en' || saved === 'es') return saved
  } catch { /* storage unavailable */ }
  return navigator.language?.toLowerCase().startsWith('es') ? 'es' : 'en'
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang)
  const setLang = (l: Lang) => {
    setLangState(l)
    try { localStorage.setItem('siren-lang', l) } catch { /* ignore */ }
  }
  return <Ctx.Provider value={{ lang, t: S[lang], setLang }}>{children}</Ctx.Provider>
}

export const useI18n = () => useContext(Ctx)
export const strings = (l: Lang) => S[l]

// Times are shown in the replayed area's local time zone (set from /api/state).
let TZ = 'America/Chicago'
export function setTimeZone(tz: string) { TZ = tz }
export function getTimeZone() { return TZ }

export function fmtLocal(iso: string | null | undefined, lang: Lang = 'en', withDay = false): string {
  if (!iso) return '—'
  return new Date(iso).toLocaleString(lang === 'es' ? 'es-US' : 'en-US', {
    hour: 'numeric', minute: '2-digit', timeZone: TZ, ...(withDay ? { weekday: 'short' } : {}),
  })
}
